    private void cargarFunciones(int idPelicula) {
        Conexion conexion = new Conexion(); // Asume que ya tienes una clase para manejar conexiones
        try (Connection conn = conexion.conectar()) {
            // Obtener el nombre de la película y las funciones
            String sql = "SELECT p.nombre, f.horario_inicio, f.horario_fin FROM funciones f JOIN peliculas p ON f.id_pelicula = p.idpeliculas WHERE p.idpeliculas = ?";
            PreparedStatement stmt = conn.prepareStatement(sql);
            stmt.setInt(1, idPelicula);
            ResultSet rs = stmt.executeQuery();
            DefaultComboBoxModel<String> model = new DefaultComboBoxModel<>();
            String nombrePelicula = "";
            if (rs.next()) {
                nombrePelicula = rs.getString("nombre");
                do {
                    String horarioInicio = new SimpleDateFormat("hh:mm a").format(rs.getTime("horario_inicio"));
                    String horarioFin = new SimpleDateFormat("hh:mm a").format(rs.getTime("horario_fin"));
                    model.addElement("Inicio: " + horarioInicio + " - Fin: " + horarioFin);
                } while (rs.next());
            }
            cBoxFunciones.setModel(model);
            txtNombrePelicula.setText(nombrePelicula);
        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error al cargar funciones.");
        }
    }

