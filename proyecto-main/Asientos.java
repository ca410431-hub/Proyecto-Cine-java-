    public JToggleButton [][] jtbAsientos = new JToggleButton[filas][columnas];
    public void asientos() {
        int filas = 6; // horizontal
        int columnas = 5; // vertical
        int largoboton = 140;
        int anchoboton = 60;
        int ejeX = 20; // lados
        int ejeY = 20;  // arriba abajo

        jtbAsientos = new JToggleButton[filas][columnas];

        for (int i = 0; i < filas; i++) {
            for (int j = 0; j < columnas; j++) {
                jtbAsientos[i][j] = new JToggleButton();
                jtbAsientos[i][j].setBounds(ejeX, ejeY, largoboton, anchoboton);
                jtbAsientos[i][j].setText("A " + (i * columnas + j + 1));
                jtbAsientos[i][j].setBackground(Color.green);
                jtbAsientos[i][j].addActionListener(new ActionListener() {
                    @Override
                    public void actionPerformed(ActionEvent e) {
                        JToggleButton button = (JToggleButton) e.getSource();
                        if (button.isSelected()) {
                            button.setBackground(Color.red);
                            button.setEnabled(false);
                        }
                    }
                });

                jPanelAsientos.add(jtbAsientos[i][j]);
                ejeX += 170; // separación entre columnas
            }
            ejeX = 20; // posición inicial de los botones
            ejeY += 70; // separación de los botones
        }
    }


