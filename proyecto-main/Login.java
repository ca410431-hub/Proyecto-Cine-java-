    private void btnIniciarsesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarsesionActionPerformed
        // TODO add your handling code here:
        // Agarrar email
        String email = txtUsuario.getText();

        // Agarrar password
        String password = new String(passfContrasena.getPassword());

        // Crear una nueva instancia de Conexion
        Conexion conexion = new Conexion("cinedl", "root", "");

        // Realizar la conexión
        Connection conn = conexion.conectar();

        // Realizar la consulta
        String sql = "SELECT idusuario, nombre, apellidoPaterno, apellidoMaterno, email, password, level "
                + "FROM usuario u "
                + "WHERE u.email = ? AND u.password = ? AND u.level = 1";

        // Comparar si los datos ingresados están en la base de datos
        try (PreparedStatement stmt = conn.prepareStatement(sql)) {

            stmt.setString(1, email);
            stmt.setString(2, password);

            ResultSet rs = stmt.executeQuery();

            if (rs.next()) {
                // Usuario y contraseña son correctos
                JOptionPane.showMessageDialog(null, "Bienvenido " + rs.getString("nombre") + " " + rs.getString("apellidoPaterno") + "!");
                //abrir ventana pagina principal
                PaginaPrincipal paginaPrincipal = new PaginaPrincipal();
                paginaPrincipal.setVisible(true);
                this.dispose();

            } else {
                // Usuario y/o contraseña incorrectos
                JOptionPane.showMessageDialog(null, "Email y/o contraseña incorrectos");
            }

        } catch (SQLException ex) {
            ex.printStackTrace();
        } finally {
            conexion.desconectar();
        }
        
    }//GEN-LAST:event_btnIniciarsesionActionPerformed

