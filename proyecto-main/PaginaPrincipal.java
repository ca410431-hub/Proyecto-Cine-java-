    private int obtenerIdPelicula(String nombrePelicula) {
        Conexion conexion = new Conexion(); // Asume que tienes una clase para manejar conexiones
        try (Connection conn = conexion.conectar()) {
            String sql = "SELECT idpeliculas FROM peliculas WHERE nombre = ?";
            PreparedStatement stmt = conn.prepareStatement(sql);
            stmt.setString(1, nombrePelicula);
            ResultSet rs = stmt.executeQuery();
            if (rs.next()) {
                return rs.getInt("idpeliculas");
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error de conexión con la base de datos.");
            e.printStackTrace();
        }
        return -1; // Retornar -1 si no se encuentra la película o hay un error
    }

