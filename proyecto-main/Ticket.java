    public Ticket(String nombrePelicula, ArrayList<String> asientosSeleccionados, String horaFuncion) {
        initComponents();
        this.nombrePelicula = nombrePelicula;
        this.asientosSeleccionados = asientosSeleccionados;
        this.horaFuncion = horaFuncion;
        mostrarInformacion();

    }

    private void mostrarInformacion() {
        lblTituloPelicula.setText("Película: " + nombrePelicula);
        StringBuilder sb = new StringBuilder();
        sb.append("Hora de función: " + horaFuncion + "\n"); // Agregar la hora de función
        sb.append("Asientos seleccionados:\n");
        for (String asiento : asientosSeleccionados) {
            sb.append(asiento + "\n");
        }
        jTextArea1.setText(sb.toString());
    }


