    // Método para establecer la descripción de la película
    public void setDescripcion(String nombrePelicula) {
        this.nombrePelicula = nombrePelicula;  // Asegúrate de almacenar el nombre para uso posterior
        lblNombrePelicula.setText(nombrePelicula); // Establece el nombre en el label

        Conexion conexion = new Conexion(); // Asume que tienes una clase para gestionar la conexión
        SimpleDateFormat sdf = new SimpleDateFormat("hh:mm a"); // Formateador de fecha para mostrar AM/PM

        try (Connection conn = conexion.conectar()) {
            String sql = "SELECT p.descripcion, p.duracion, p.precio, p.subtitulado, p.doblado, p.formato, p.imagen, " +
                    "f.horario_inicio, f.horario_fin, s.nombre_sala " +
                    "FROM peliculas p " +
                    "JOIN funciones f ON p.idpeliculas = f.id_pelicula " +
                    "JOIN salas s ON f.id_sala = s.id_sala " +
                    "WHERE p.nombre = ?";
            PreparedStatement stmt = conn.prepareStatement(sql);
            stmt.setString(1, nombrePelicula);
            ResultSet rs = stmt.executeQuery();
            StringBuilder sb = new StringBuilder();
            boolean found = false;
            while (rs.next()) {
                if (!found) {
                    String pathToImage = "C:\\Users\\lgtro\\OneDrive\\Documentos\\NetBeansProjects\\UNEDL-PROGRAMACION-VISUAL-2024\\src\\CINEDL\\Imagenes\\" + rs.getString("imagen");
                    ImageIcon imageIcon = new ImageIcon(new ImageIcon(pathToImage).getImage().getScaledInstance(180, 260, Image.SCALE_DEFAULT));
                    labelImagen.setIcon(imageIcon);

                    sb.append(String.format(
                            "Descripción: %s\nDuración: %d minutos\nPrecio: $%.2f\nSubtitulado: %s\nDoblado: %s\nFormato: %s\n\n",
                            rs.getString("descripcion"),
                            rs.getInt("duracion"),
                            rs.getDouble("precio"),
                            rs.getBoolean("subtitulado") ? "Sí" : "No",
                            rs.getBoolean("doblado") ? "Sí" : "No",
                            rs.getString("formato")
                    ));
                    found = true;
                }
                sb.append(String.format("Función en sala %s: %s - %s\n",
                        rs.getString("nombre_sala"),
                        sdf.format(rs.getTime("horario_inicio")),
                        sdf.format(rs.getTime("horario_fin"))));
            }
            if (found) {
                textAreaDescripcion.setText(sb.toString());
            } else {
                textAreaDescripcion.setText("Película no encontrada o no hay funciones disponibles.");
            }
        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error al conectar con la base de datos.");
        }
    }

    // En la clase VentanaDescripcion
    private List<String> obtenerFunciones(String nombrePelicula) {
        List<String> funciones = new ArrayList<>();

        Conexion conexion = new Conexion();

        try (Connection conn = conexion.conectar()) {
            String sql = "SELECT horario_inicio FROM funciones WHERE id_pelicula = (SELECT idpeliculas FROM peliculas WHERE nombre = ?)";
            PreparedStatement stmt = conn.prepareStatement(sql);
            stmt.setString(1, nombrePelicula);
            ResultSet rs = stmt.executeQuery();
            while (rs.next()) {
                // Formatear la hora según sea necesario, posiblemente usando SimpleDateFormat para formato de 12 horas
                String horario = rs.getString("horario_inicio"); // Simplificado para ilustración
                funciones.add(horario);
            }
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
        return funciones;
    }






